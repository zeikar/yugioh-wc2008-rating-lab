/** Deck styles, the app's own labels for how a list tries to win. */
export const DECK_STYLES = {
  beatdown: 'Beatdown',
  burn: 'Burn',
  control: 'Control',
  stall: 'Stall',
  ritual: 'Ritual',
  fusion: 'Fusion',
  swarm: 'Swarm',
  graveyard: 'Graveyard',
  banish: 'Banish',
  lifegain: 'Lifegain',
  gamble: 'Gamble',
  'alt-win': 'Alt win',
} as const
export type DeckStyle = keyof typeof DECK_STYLES

/** The one section outside the main deck: WC2008 predates Synchro. */
export const EXTRA_DECK = 'Fusion monsters'

export interface DeckSection {
  /** Yugipedia's grouping: "Effect monsters", "Spells", and EXTRA_DECK, always last. */
  title: string
  cards: readonly (readonly [name: string, copies: number])[]
}

export interface Deck {
  /** As the English release names it on the opponent card. */
  name: string
  jaName: string
  /** Main style first. */
  styles: readonly DeckStyle[]
  /** One line on how the list plays. */
  summary: string
  /** Yugipedia page the list and the portrait come from. */
  wiki: string
  sections: readonly DeckSection[]
}

/** Card count of the main deck, or of the Extra Deck. */
export function deckSize(deck: Deck, extra: boolean): number {
  return deck.sections.filter((s) => (s.title === EXTRA_DECK) === extra).reduce((n, s) => n + s.cards.reduce((m, [, copies]) => m + copies, 0), 0)
}

